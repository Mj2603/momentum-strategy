"""Run the 12-1 momentum backtest on seeded SYNTHETIC data and write results/.

Scenarios (see synthetic.py):
  null   - all stocks share the same drift; true expected momentum return is 0.
  drift  - persistent per-stock drift (dispersion 1%/month); momentum is
           profitable by construction.
Each scenario is run at 0, 10 and 50 bps one-way cost per unit of turnover.

Usage: python run_experiment.py
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from momentum_strategy import performance_metrics, run_backtest
from synthetic import synthetic_monthly_prices

SEED = 42
N_STOCKS = 100
N_MONTHS = 240
TOP_N = 10
SCENARIOS = {"null": 0.0, "drift": 0.01}
COSTS_BPS = [0, 10, 50]
OUT = Path(__file__).resolve().parent / "results"


def main() -> pd.DataFrame:
    rows = []
    for name, disp in SCENARIOS.items():
        prices = synthetic_monthly_prices(
            n_stocks=N_STOCKS, n_months=N_MONTHS, drift_dispersion=disp, seed=SEED
        )
        for c in COSTS_BPS:
            res = run_backtest(prices, lookback=12, skip=1, top_n=TOP_N, cost_bps=c)
            m = performance_metrics(res["net_return"])
            rows.append(
                {
                    "scenario": name,
                    "cost_bps": c,
                    "months": int(m["months"]),
                    "ann_mean": m["ann_mean"],
                    "ann_vol": m["ann_vol"],
                    "sharpe": m["sharpe"],
                    "t_stat": m["t_stat_mean"],
                    "max_drawdown": m["max_drawdown"],
                    "avg_turnover": res["turnover"].mean(),
                }
            )
    table = pd.DataFrame(rows)
    OUT.mkdir(exist_ok=True)
    table.to_csv(OUT / "synthetic_results.csv", index=False, float_format="%.6f")

    fmt = table.copy()
    for col in ["ann_mean", "ann_vol", "max_drawdown"]:
        fmt[col] = (fmt[col] * 100).map("{:.2f}%".format)
    for col in ["sharpe", "t_stat", "avg_turnover"]:
        fmt[col] = fmt[col].map("{:.2f}".format)
    header = "| " + " | ".join(fmt.columns) + " |\n|" + "---|" * len(fmt.columns) + "\n"
    body = "".join("| " + " | ".join(str(v) for v in r) + " |\n" for r in fmt.itertuples(index=False))
    md = (
        "# Results (SYNTHETIC data)\n\n"
        "Data: SYNTHETIC, generated by `synthetic.py` with seed "
        f"{SEED}, {N_STOCKS} stocks, {N_MONTHS} months, monthly vol 8%. "
        "Not market data.\n\n"
        f"Strategy: 12-1 momentum, long top {TOP_N} / short bottom {TOP_N}, equal weight, "
        "monthly rebalance. Returns are net of the stated cost per unit of turnover.\n\n"
        "- `null`: no cross-sectional drift differences, so the true expected return is 0.\n"
        "- `drift`: per-stock drift with 1%/month dispersion, so momentum works by construction.\n\n"
        + header
        + body
        + "\nGenerated by `python run_experiment.py`.\n"
    )
    (OUT / "synthetic_results.md").write_text(md)
    print(md)
    return table


if __name__ == "__main__":
    main()
